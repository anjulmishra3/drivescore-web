def arrows(ax, xs, ys, color, n=1):
    for i in range(0, len(xs) - 1, max(1, len(xs)//(n+1) or 1)):
        ax.annotate("", xy=(xs[i+1], ys[i+1]), xytext=(xs[i], ys[i]),
                    arrowprops=dict(arrowstyle="-|>", color=color, lw=1.4))

